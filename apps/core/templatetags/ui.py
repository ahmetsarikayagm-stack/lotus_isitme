@register.simple_tag
def icon(name, css="w-5 h-5"):
    paths = ICONS.get(name)
    if not paths:
        return ""
    inner = format_html_join("", '<path stroke-linecap="round" stroke-linejoin="round" d="{}"/>', ((p,) for p in paths))
    return mark_safe(
        f'<svg xmlns="http://www.w3.org/2000/svg" fill="none" viewBox="0 0 24 24" stroke-width="1.6" '
        f'stroke="currentColor" class="{css}" aria-hidden="true">{inner}</svg>'
    )


@register.filter
def widget_type(bound_field):
    return bound_field.field.widget.__class__.__name__


@register.filter
def field_type(bound_field):
    return bound_field.field.__class__.__name__


@register.filter
def is_wide(bound_field):
    return widget_type(bound_field) in {"Textarea", "FileInput", "CheckboxSelectMultiple"}


@register.filter
def basename(value):
    return os.path.basename(str(value))
